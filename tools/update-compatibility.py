#!/usr/bin/env python3
"""Regenerate the embedded catalogue lists from the OpenPak website's catalogue.

Writes client/openpak/compatibility_list.inc (OpenPak's online status per title) and
client/openpak/playability_list.inc (how far each emulator runs the title itself).

Ported from Ryujinx's scripts/update-openpak-compatibility.py, so every Switch emulator ships the
same list. The website database is the only source of title status: this keeps its Switch titles
at live, beta or alpha. A playable title without a title_id can't be looked up by an emulator, so
it is listed and the script fails without writing -- set the id on the website, not here.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

URL = "https://openpak.org/api/v1/catalog.json"
CLIENT = Path(__file__).resolve().parent.parent / "client" / "openpak"
OUT = CLIENT / "compatibility_list.inc"
PLAY_OUT = CLIENT / "playability_list.inc"
PLAYABLE = {"live", "beta", "alpha"}
# The words the catalogue uses for how far a title runs. Anything else is untested to the client,
# so it is left out rather than shipped for the client to throw away.
PLAYABILITY = {"playable", "ingame", "menus", "boots", "nothing"}


def literal(text):
    return json.dumps(text, ensure_ascii=False)  # a JSON string is a valid C++ string literal here


def main():
    request = urllib.request.Request(URL, headers={"User-Agent": "openpak-client-compatibility"})
    with urllib.request.urlopen(request, timeout=60) as response:
        catalog = json.load(response)

    titles = [e for e in catalog if e["kind"] == "title" and e["console"] == "Switch" and e["status"] in PLAYABLE]
    missing = [e["name"] for e in titles if not re.fullmatch(r"[0-9A-F]{16}", e.get("title_id") or "")]
    if missing:
        print(f"{len(missing)} playable Switch title(s) have no title_id on the website:", file=sys.stderr)
        for name in missing:
            print(f"  {name}", file=sys.stderr)
        sys.exit(1)

    rows = sorted(titles, key=lambda e: e["name"].casefold())
    lines = ["// Generated by tools/update-compatibility.py from " + URL + ". Do not edit.\n"]
    for e in rows:
        lines.append("{0x%sULL, %s, %s, %s},\n" % (e["title_id"], literal(e["name"]),
                                                  literal(e["backend"]), literal(e["status"])))
    OUT.write_text("".join(lines))
    print(f"{len(rows)} titles written to {OUT}")

    # Playability is per emulator and covers every Switch title the catalogue knows, playable
    # online or not. The website is adding the field: no field anywhere is no rows, not an error,
    # so a build off an older site still works.
    play = ["// Generated by tools/update-compatibility.py from " + URL + ". Do not edit.\n"]
    seen = 0
    for e in sorted((e for e in catalog if e["kind"] == "title" and e["console"] == "Switch"),
                    key=lambda e: e["name"].casefold()):
        title_id = e.get("title_id") or ""
        if not re.fullmatch(r"[0-9A-F]{16}", title_id):
            continue  # nothing to look up by; the status list above is where a missing id is fatal
        for client, word in sorted((e.get("playability") or {}).items()):
            if word in PLAYABILITY:
                play.append("{0x%sULL, %s, %s},\n" % (title_id, literal(client), literal(word)))
                seen += 1
    PLAY_OUT.write_text("".join(play))
    print(f"{seen} playability row(s) written to {PLAY_OUT}")


if __name__ == "__main__":
    main()
